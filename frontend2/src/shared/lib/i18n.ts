//   import { useLanguage } from "../../shared/lib/i18n"
//   const { lang, setLang, t } = useLanguage()
//   <h1>{t("home.hero_title")}</h1>
//
// Adding a new key: append it to STRINGS_ZH and STRINGS_EN with the
